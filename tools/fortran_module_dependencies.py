#!/usr/bin/env python3
"""Write the Fortran module dependencies of src/*.f90 as Make rules.

A source that USEs a module must be compiled after the source that defines
it, and recompiled when that source changes (its .mod file may have changed).
For every src/a.f90 that uses a module defined in src/b.f90 (b != a) this
writes

    src/a.o: src/b.o

and for every src/a.f90 that INCLUDEs a file present in src/

    src/a.o: src/x.inc

Modules defined outside src/ (HDF5, MPI, the intrinsic modules) are skipped:
this Makefile does not rebuild them.  A module defined in two sources is an
error, so a stale copy left in src/ is caught here.  Output is sorted, so the
file changes only when a dependency does.

    python3 tools/fortran_module_dependencies.py src > src/Makefile.dep

Adapted from MoCHII_v1.00/tools/fortran_module_dependencies.py.
"""
import re
import sys
from pathlib import Path

MODULE = re.compile(r'^\s*module\s+(\w+)\s*(!.*)?$', re.IGNORECASE)
USE = re.compile(r'^\s*use\s*(?:,\s*non_intrinsic\s*)?(?:::)?\s*(\w+)', re.IGNORECASE)
INTRINSIC = re.compile(r'^\s*use\s*,\s*intrinsic', re.IGNORECASE)
INCLUDE = re.compile(r'''^\s*include\s*['"]([^'"]+)['"]''', re.IGNORECASE)


def scan(path):
    defined, used, included = set(), set(), set()
    for line in path.read_text(errors='replace').splitlines():
        m = INCLUDE.match(line)
        if m:
            included.add(m.group(1))
            continue
        if INTRINSIC.match(line):
            continue
        m = MODULE.match(line)
        if m and m.group(1).lower() != 'procedure':
            defined.add(m.group(1).lower())
            continue
        m = USE.match(line)
        if m:
            used.add(m.group(1).lower())
    return defined, used, included


def main():
    src = Path(sys.argv[1] if len(sys.argv) > 1 else 'src')
    files = sorted(src.glob('*.f90'))
    owner, uses, incs = {}, {}, {}
    for f in files:
        defined, used, included = scan(f)
        incs[f] = sorted(src / i for i in included if (src / i).is_file())
        for mod in defined:
            if mod in owner:
                sys.exit(f'module {mod} defined in both {owner[mod]} and {f}')
            owner[mod] = f
        uses[f] = used
    print('# Generated by tools/fortran_module_dependencies.py -- do not edit.')
    print('# Regenerated by the Makefile whenever a source under src/ changes.')
    for f in files:
        deps = sorted({owner[m] for m in uses[f] if m in owner and owner[m] != f})
        items = [str(d.with_suffix('.o')) for d in deps] + [str(i) for i in incs[f]]
        if items:
            print(f'{f.with_suffix(".o")}: ' + ' '.join(items))


if __name__ == '__main__':
    main()
